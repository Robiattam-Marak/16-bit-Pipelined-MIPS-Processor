module instruction_memory(

    input [15:0] address,

    output [15:0] instruction,

    output [4:0] opcode,

    output [2:0] rs,
    output [2:0] rt,
    output [2:0] rd,

    output [4:0] imm_5,
    output [10:0] imm_11,

    output [1:0] func
);

    //--------------------------------------------------
    // ROM
    //--------------------------------------------------
    reg [15:0] ROM [0:255];

    integer i;

    //--------------------------------------------------
    // PROGRAM
    //--------------------------------------------------
    initial begin

        for(i=0;i<256;i=i+1)
            ROM[i] = 16'h0000;

        //----------------------------------------------
        // R-Type ADD
        // opcode=0 func=0
        //----------------------------------------------
        ROM[0] = 16'b00000_010_011_001_00;

        //----------------------------------------------
        // R-Type SUB
        // opcode=1 func=1
        //----------------------------------------------
        ROM[1] = 16'b00001_001_010_100_01;

        //----------------------------------------------
        // ADDI
        // opcode=7
        //----------------------------------------------
        ROM[2] = 16'b00111_001_010_00101;

        //----------------------------------------------
        // LW
        // opcode=12
        //----------------------------------------------
        ROM[3] = 16'b01100_001_010_00000;

        //----------------------------------------------
        // SW
        // opcode=13
        //----------------------------------------------
        ROM[4] = 16'b01101_001_010_00001;

        //----------------------------------------------
        // J
        // opcode=30
        //----------------------------------------------
        ROM[5] = 16'b11110_00000000010;

    end

    //--------------------------------------------------
    // WORD ADDRESSING
    //--------------------------------------------------
    assign instruction = ROM[address[7:0]];

    //--------------------------------------------------
    // FIELD EXTRACTION
    //--------------------------------------------------
    assign opcode = instruction[15:11];

    assign rs = instruction[10:8];

    assign rt = instruction[7:5];

    assign rd = instruction[4:2];

    assign func = instruction[1:0];

    assign imm_5 = instruction[4:0];

    assign imm_11 = instruction[10:0];

endmodule