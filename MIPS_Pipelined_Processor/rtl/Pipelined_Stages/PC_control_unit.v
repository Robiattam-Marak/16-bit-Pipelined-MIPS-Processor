//=========================================================
// PC CONTROL UNIT
//=========================================================
module pc_control_unit(

    input JR,
    input J,
    input JAL,
    input BR,

    output reg [1:0] PCControl,
    output reg Kill1

);

always @(*) begin

    //---------------------------------------------
    // defaults
    //---------------------------------------------
    PCControl = 2'b00;

    Kill1 = 1'b0;

    //---------------------------------------------
    // Branch
    //---------------------------------------------
    if(BR) begin

        PCControl = 2'b01;

        Kill1 = 1'b1;

    end

    //---------------------------------------------
    // Jump
    //---------------------------------------------
    if(J || JAL) begin

        PCControl = 2'b10;

        Kill1 = 1'b1;

    end

    //---------------------------------------------
    // JR
    //---------------------------------------------
    if(JR) begin

        PCControl = 2'b11;

        Kill1 = 1'b1;

    end

end

endmodule