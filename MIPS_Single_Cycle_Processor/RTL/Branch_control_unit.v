
module branch_control_unit(

    input  [4:0] opcode,
    input        Zero_Flag,
    input        Set,

    output reg   Branch

);

always @(*) begin

    //-----------------------------------------------------
    // DEFAULT
    //-----------------------------------------------------
    Branch = 1'b0;

    //-----------------------------------------------------
    // BRANCH DECODE
    //-----------------------------------------------------
    case(opcode)

        //---------------------------------
        // BEQ
        //---------------------------------
        5'd14:
            Branch = Zero_Flag;

        //---------------------------------
        // BNE
        //---------------------------------
        5'd15:
            Branch = ~Zero_Flag;

        //---------------------------------
        // BLT
        //---------------------------------
        5'd16:
            Branch = Set;

        //---------------------------------
        // BGE
        //---------------------------------
        5'd17:
            Branch = ~Set;

        //---------------------------------
        // DEFAULT
        //---------------------------------
        default:
            Branch = 1'b0;

    endcase

end

endmodule