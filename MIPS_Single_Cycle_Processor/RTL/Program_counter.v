//=========================================================
// PROGRAM COUNTER (PC)
// 16-bit MIPS Processor
//=========================================================
module program_counter (

    input clk,
    input reset,

    //-----------------------------------------------------
    // CONTROL SIGNALS
    //-----------------------------------------------------
    input Branch,
    input J,
    input Jr,

    //-----------------------------------------------------
    // IMMEDIATE VALUES
    //-----------------------------------------------------
    input [4:0] imm_5,
    input [10:0] imm_11,

    //-----------------------------------------------------
    // REGISTER VALUE FOR JR
    //-----------------------------------------------------
    input [15:0] Rs,

    //-----------------------------------------------------
    // CURRENT PC
    //-----------------------------------------------------
    output reg [15:0] PC,

    //-----------------------------------------------------
    // PC + 1
    //-----------------------------------------------------
    output [15:0] PC_plus_1
);

    //-----------------------------------------------------
    // INTERNAL WIRES
    //-----------------------------------------------------
    wire [15:0] branch_offset;
    wire [15:0] jump_offset;

    wire [15:0] branch_target;
    wire [15:0] jump_target;

    reg  [15:0] next_pc;

    //-----------------------------------------------------
    // SIGN EXTENSION
    //-----------------------------------------------------
    assign branch_offset =
            {{11{imm_5[4]}}, imm_5};

    assign jump_offset =
            {{5{imm_11[10]}}, imm_11};

    //-----------------------------------------------------
    // PC + 1
    //-----------------------------------------------------
    assign PC_plus_1 = PC + 16'd1;

    //-----------------------------------------------------
    // TARGET ADDRESSES
    //-----------------------------------------------------
    assign branch_target =
            PC_plus_1 + branch_offset;

    assign jump_target =
            PC_plus_1 + jump_offset;

    //-----------------------------------------------------
    // NEXT PC LOGIC
    //-----------------------------------------------------
    always @(*)
    begin

        //-------------------------------------------------
        // DEFAULT
        //-------------------------------------------------
        next_pc = PC_plus_1;

        //-------------------------------------------------
        // BRANCH
        //-------------------------------------------------
        if(Branch)
            next_pc = branch_target;

        //-------------------------------------------------
        // JUMP
        //-------------------------------------------------
        if(J)
            next_pc = jump_target;

        //-------------------------------------------------
        // JR
        //-------------------------------------------------
        if(Jr)
            next_pc = Rs;

    end

    //-----------------------------------------------------
    // PC REGISTER
    //-----------------------------------------------------
    always @(posedge clk or posedge reset)
    begin

        if(reset)
            PC <= 16'd0;

        else
            PC <= next_pc;

    end

endmodule