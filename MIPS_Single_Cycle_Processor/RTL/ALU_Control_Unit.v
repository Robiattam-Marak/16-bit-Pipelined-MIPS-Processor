//=========================================================
// ALU CONTROL UNIT
//=========================================================
module alu_control_unit(

    input  [4:0] opcode,
    input  [1:0] func,

    output reg Carry_In,
    output reg Ainvert,
    output reg Binvert,

    output reg [2:0] Operation,

    output reg [1:0] ResCtrl,
    output reg [1:0] ShfCtrl,

    output reg Jr
);

always @(*) begin

    //-----------------------------------------------------
    // DEFAULT VALUES
    //-----------------------------------------------------
    Carry_In = 1'b0;
    Ainvert  = 1'b0;
    Binvert  = 1'b0;

    Operation = 3'b000;

    ResCtrl = 2'b00;
    ShfCtrl = 2'b00;

    Jr = 1'b0;

    //-----------------------------------------------------
    // OPCODE DECODE
    //-----------------------------------------------------
    case(opcode)

    //-----------------------------------------------------
    // R-TYPE LOGIC
    //-----------------------------------------------------
    5'd0:
    begin
        case(func)

            // AND
            2'd0:
            begin
                Operation = 3'b000;
            end

            // OR
            2'd1:
            begin
                Operation = 3'b001;
            end

            // XOR
            2'd2:
            begin
                Operation = 3'b100;
            end

            // NOR
            2'd3:
            begin
                Ainvert   = 1'b1;
                Binvert   = 1'b1;
                Operation = 3'b000;
            end

        endcase
    end

    //-----------------------------------------------------
    // R-TYPE ARITHMETIC
    //-----------------------------------------------------
    5'd1:
    begin
        case(func)

            // ADD
            2'd0:
            begin
                Operation = 3'b010;
            end

            // SUB
            2'd1:
            begin
                Carry_In  = 1'b1;
                Binvert   = 1'b1;
                Operation = 3'b010;
            end

            // SLT
            2'd2:
            begin
                Carry_In  = 1'b1;
                Binvert   = 1'b1;
                Operation = 3'b011;
            end

            // SLTU
            2'd3:
            begin
                ResCtrl = 2'b10;
            end

        endcase
    end

    //-----------------------------------------------------
    // JR
    //-----------------------------------------------------
    5'd2:
    begin
        Jr = 1'b1;
    end

    //-----------------------------------------------------
    // ANDI
    //-----------------------------------------------------
    5'd4:
    begin
        Operation = 3'b000;
    end

    //-----------------------------------------------------
    // ORI
    //-----------------------------------------------------
    5'd5:
    begin
        Operation = 3'b001;
    end

    //-----------------------------------------------------
    // XORI
    //-----------------------------------------------------
    5'd6:
    begin
        Operation = 3'b100;
    end

    //-----------------------------------------------------
    // ADDI
    //-----------------------------------------------------
    5'd7:
    begin
        Operation = 3'b010;
    end

    //-----------------------------------------------------
    // SLL
    //-----------------------------------------------------
    5'd8:
    begin
        ResCtrl = 2'b01;
        ShfCtrl = 2'b00;
    end

    //-----------------------------------------------------
    // SRL
    //-----------------------------------------------------
    5'd9:
    begin
        ResCtrl = 2'b01;
        ShfCtrl = 2'b01;
    end

    //-----------------------------------------------------
    // SRA
    //-----------------------------------------------------
    5'd10:
    begin
        ResCtrl = 2'b01;
        ShfCtrl = 2'b10;
    end

    //-----------------------------------------------------
    // ROR
    //-----------------------------------------------------
    5'd11:
    begin
        ResCtrl = 2'b01;
        ShfCtrl = 2'b11;
    end

    //-----------------------------------------------------
    // LW
    //-----------------------------------------------------
    5'd12:
    begin
        Operation = 3'b010;
    end

    //-----------------------------------------------------
    // SW
    //-----------------------------------------------------
    5'd13:
    begin
        Operation = 3'b010;
    end

    //-----------------------------------------------------
    // BEQ
    //-----------------------------------------------------
    5'd14:
    begin
        Carry_In  = 1'b1;
        Binvert   = 1'b1;
        Operation = 3'b010;
    end

    //-----------------------------------------------------
    // BNE
    //-----------------------------------------------------
    5'd15:
    begin
        Carry_In  = 1'b1;
        Binvert   = 1'b1;
        Operation = 3'b010;
    end

    //-----------------------------------------------------
    // BLT
    //-----------------------------------------------------
    5'd16:
    begin
        Carry_In  = 1'b1;
        Binvert   = 1'b1;
        Operation = 3'b010;
    end

    //-----------------------------------------------------
    // BGE
    //-----------------------------------------------------
    5'd17:
    begin
        Carry_In  = 1'b1;
        Binvert   = 1'b1;
        Operation = 3'b010;
    end

    default:
    begin
    end

    endcase

end

endmodule