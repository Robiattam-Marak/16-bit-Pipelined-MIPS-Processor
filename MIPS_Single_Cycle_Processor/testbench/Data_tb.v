//=========================================================
// TESTBENCH : DATA MEMORY
//=========================================================
`timescale 1ns/1ps

module tb_data_memory;

    //-----------------------------------------------------
    // SIGNALS
    //-----------------------------------------------------
    reg clk;

    reg MemWr;
    reg MemRd;

    reg [15:0] address;

    reg [15:0] write_data;

    wire [15:0] read_data;

    //-----------------------------------------------------
    // DUT
    //-----------------------------------------------------
    data_memory DUT (

        .clk(clk),

        .MemWr(MemWr),
        .MemRd(MemRd),

        .address(address),

        .write_data(write_data),

        .read_data(read_data)
    );

    //-----------------------------------------------------
    // CLOCK
    //-----------------------------------------------------
    always #5 clk = ~clk;

    //-----------------------------------------------------
    // TEST
    //-----------------------------------------------------
    initial
    begin

        clk = 0;

        MemWr = 0;
        MemRd = 0;

        address = 0;
        write_data = 0;

        //-------------------------------------------------
        // WRITE TEST
        //-------------------------------------------------
        $display("===== MEMORY WRITE TEST =====");

        address = 20;

        write_data = 16'd1234;

        MemWr = 1;

        #10;

        MemWr = 0;

        //-------------------------------------------------
        // READ TEST
        //-------------------------------------------------
        $display("===== MEMORY READ TEST =====");

        address = 20;

        MemRd = 1;

        #10;

        $display("ADDRESS = %d", address);

        $display("READ DATA = %d", read_data);

        //-------------------------------------------------
        // READ PRELOADED MEMORY
        //-------------------------------------------------
        address = 10;

        #10;

        $display("ADDRESS = %d", address);

        $display("READ DATA = %d", read_data);

        //-------------------------------------------------
        // FINISH
        //-------------------------------------------------
        #20;

        $finish;

    end

endmodule