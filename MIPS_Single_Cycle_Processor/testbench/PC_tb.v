//=========================================================
// TESTBENCH : PROGRAM COUNTER
//=========================================================
`timescale 1ns/1ps

module tb_program_counter;

    //-----------------------------------------------------
    // INPUTS
    //-----------------------------------------------------
    reg clk;
    reg reset;

    reg Branch;
    reg J;
    reg Jr;

    reg [4:0] imm_5;
    reg [10:0] imm_11;

    reg [15:0] Rs;

    //-----------------------------------------------------
    // OUTPUTS
    //-----------------------------------------------------
    wire [15:0] PC;
    wire [15:0] PC_plus_1;

    //-----------------------------------------------------
    // DUT
    //-----------------------------------------------------
    program_counter DUT (

        .clk(clk),
        .reset(reset),

        .Branch(Branch),
        .J(J),
        .Jr(Jr),

        .imm_5(imm_5),
        .imm_11(imm_11),

        .Rs(Rs),

        .PC(PC),
        .PC_plus_1(PC_plus_1)
    );

    //-----------------------------------------------------
    // CLOCK
    //-----------------------------------------------------
    always #5 clk = ~clk;

    //-----------------------------------------------------
    // DISPLAY TASK
    //-----------------------------------------------------
    task show_pc;

        begin

            $display("--------------------------------");

            $display("TIME = %0t", $time);

            $display("PC = %0d", PC);

            $display("PC+1 = %0d", PC_plus_1);

            $display("--------------------------------");

        end

    endtask

    //-----------------------------------------------------
    // TEST
    //-----------------------------------------------------
    initial
    begin

        //-------------------------------------------------
        // INITIALIZE
        //-------------------------------------------------
        clk = 0;
        reset = 1;

        Branch = 0;
        J = 0;
        Jr = 0;

        imm_5 = 0;
        imm_11 = 0;

        Rs = 0;

        //-------------------------------------------------
        // RESET
        //-------------------------------------------------
        #10;

        reset = 0;

        //-------------------------------------------------
        // NORMAL PC INCREMENT
        //-------------------------------------------------
        $display("\n===== NORMAL INCREMENT =====");

        #10;
        show_pc();

        #10;
        show_pc();

        #10;
        show_pc();

        //-------------------------------------------------
        // BRANCH TEST
        //-------------------------------------------------
        $display("\n===== BRANCH TEST =====");

        Branch = 1;

        imm_5 = 5;

        #10;

        show_pc();

        Branch = 0;

        //-------------------------------------------------
        // NORMAL EXECUTION
        //-------------------------------------------------
        #10;

        show_pc();

        //-------------------------------------------------
        // JUMP TEST
        //-------------------------------------------------
        $display("\n===== JUMP TEST =====");

        J = 1;

        imm_11 = 20;

        #10;

        show_pc();

        J = 0;

        //-------------------------------------------------
        // NORMAL EXECUTION
        //-------------------------------------------------
        #10;

        show_pc();

        //-------------------------------------------------
        // JR TEST
        //-------------------------------------------------
        $display("\n===== JR TEST =====");

        Jr = 1;

        Rs = 100;

        #10;

        show_pc();

        Jr = 0;

        //-------------------------------------------------
        // NORMAL EXECUTION
        //-------------------------------------------------
        #10;

        show_pc();

        //-------------------------------------------------
        // NEGATIVE BRANCH TEST
        //-------------------------------------------------
        $display("\n===== NEGATIVE BRANCH =====");

        Branch = 1;

        imm_5 = 5'b11110; // -2

        #10;

        show_pc();

        Branch = 0;

        //-------------------------------------------------
        // FINISH
        //-------------------------------------------------
        #20;

        $finish;

    end

endmodule