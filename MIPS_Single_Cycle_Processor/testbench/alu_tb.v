//=========================================================
// COMPLETE TESTBENCH FOR 16-BIT MIPS ALU
// Tests ALL operations
//=========================================================
`timescale 1ns/1ps

module tb_mips16_alu;

    //-----------------------------------------------------
    // INPUTS
    //-----------------------------------------------------
    reg [15:0] A;
    reg [15:0] B;

    reg Ainvert;
    reg Binvert;

    reg [2:0] operation;

    reg shift_enable;
    reg [1:0] shift_op;

    //-----------------------------------------------------
    // OUTPUTS
    //-----------------------------------------------------
    wire [15:0] Result;
    wire Zero_Flag;
    wire CarryOut;

    //-----------------------------------------------------
    // DUT
    //-----------------------------------------------------
    mips16_alu DUT (

        .A(A),
        .B(B),

        .Ainvert(Ainvert),
        .Binvert(Binvert),

        .operation(operation),

        .shift_enable(shift_enable),
        .shift_op(shift_op),

        .Result(Result),
        .Zero_Flag(Zero_Flag),
        .CarryOut(CarryOut)
    );

    //-----------------------------------------------------
    // TASK : DISPLAY RESULTS
    //-----------------------------------------------------
    task show_result;

        begin

            $display("------------------------------------");
            $display("TIME = %0t", $time);

            $display("A = %b (%0d)", A, A);
            $display("B = %b (%0d)", B, B);

            $display("RESULT = %b (%0d)", Result, Result);

            $display("ZERO = %b", Zero_Flag);
            $display("CARRY = %b", CarryOut);

            $display("------------------------------------");

        end

    endtask

    //-----------------------------------------------------
    // INITIAL BLOCK
    //-----------------------------------------------------
    initial
    begin

        //-------------------------------------------------
        // INITIALIZE
        //-------------------------------------------------
        A = 0;
        B = 0;

        Ainvert = 0;
        Binvert = 0;

        operation = 3'b000;

        shift_enable = 0;
        shift_op = 2'b00;

        #10;

        //=================================================
        // ADD TEST
        //=================================================
        $display("\n******** ADD TEST ********");

        A = 16'd25;
        B = 16'd10;

        Ainvert = 0;
        Binvert = 0;

        operation = 3'b010;

        shift_enable = 0;

        #10;

        show_result();

        //=================================================
        // SUB TEST
        //=================================================
        $display("\n******** SUB TEST ********");

        A = 16'd25;
        B = 16'd10;

        Ainvert = 0;
        Binvert = 1;

        operation = 3'b110;

        #10;

        show_result();

        //=================================================
        // AND TEST
        //=================================================
        $display("\n******** AND TEST ********");

        A = 16'b1100110011001100;
        B = 16'b1010101010101010;

        Binvert = 0;

        operation = 3'b000;

        #10;

        show_result();

        //=================================================
        // OR TEST
        //=================================================
        $display("\n******** OR TEST ********");

        operation = 3'b001;

        #10;

        show_result();

        //=================================================
        // XOR TEST
        //=================================================
        $display("\n******** XOR TEST ********");

        operation = 3'b011;

        #10;

        show_result();

        //=================================================
        // NOR TEST
        //=================================================
        $display("\n******** NOR TEST ********");

        operation = 3'b100;

        #10;

        show_result();

        //=================================================
        // SLT TEST
        //=================================================
        $display("\n******** SLT TEST ********");

        A = 16'd5;
        B = 16'd10;

        Binvert = 1;

        operation = 3'b111;

        #10;

        show_result();

        //=================================================
        // ZERO FLAG TEST
        //=================================================
        $display("\n******** ZERO FLAG TEST ********");

        A = 16'd15;
        B = 16'd15;

        Binvert = 1;

        operation = 3'b110;

        #10;

        show_result();

        //=================================================
        // SLL TEST
        //=================================================
        $display("\n******** SLL TEST ********");

        shift_enable = 1;

        A = 16'b0000000000000011;

        B = 16'd2;

        shift_op = 2'b00;

        #10;

        show_result();

        //=================================================
        // SRL TEST
        //=================================================
        $display("\n******** SRL TEST ********");

        A = 16'b0000000000010000;

        B = 16'd2;

        shift_op = 2'b01;

        #10;

        show_result();

        //=================================================
        // SRA TEST
        //=================================================
        $display("\n******** SRA TEST ********");

        A = 16'b1000000000000000;

        B = 16'd3;

        shift_op = 2'b10;

        #10;

        show_result();

        //=================================================
        // ROR TEST
        //=================================================
        $display("\n******** ROR TEST ********");

        A = 16'b1001000000000001;

        B = 16'd4;

        shift_op = 2'b11;

        #10;

        show_result();

        //=================================================
        // OVERFLOW STYLE ADD TEST
        //=================================================
        $display("\n******** LARGE ADD TEST ********");

        shift_enable = 0;

        A = 16'hFFFF;
        B = 16'h0001;

        Binvert = 0;

        operation = 3'b010;

        #10;

        show_result();

        //=================================================
        // NEGATIVE SUB TEST
        //=================================================
        $display("\n******** NEGATIVE SUB TEST ********");

        A = 16'd5;
        B = 16'd10;

        Binvert = 1;

        operation = 3'b110;

        #10;

        show_result();

        //=================================================
        // FINISH
        //=================================================
        $display("\n========== ALL TESTS COMPLETED ==========");

        #20;
        $finish;

    end

endmodule